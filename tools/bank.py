"""Pre-generate several full tests so you can take one whenever you like (`make next`).

usage: python tools/bank.py [N=3] [--level easy|medium|hard|mixed] [--parallel 1]

Each test is generated by a separate headless Claude Code run (`/toefl-generate full`). Runs are
sequential by default; --parallel 2 is faster but uses your Claude usage limits twice as fast.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

from common import ROOT, TESTS_DIR, usage_limit_message

FLAGS = ["--permission-mode", "acceptEdits", "--allowedTools", "Read", "Write", "Edit", "Glob", "Grep", "Agent", "Skill",
         "Bash(python tools/*)", "Bash(python3 tools/*)"]


def run_generation(prompt: str, log, claude: str | None = None) -> list[str]:
    """Run one headless Claude Code generation; return ids of the tests it created."""
    claude = claude or os.environ.get("CLAUDE_BIN") or shutil.which("claude")
    if not claude:
        raise RuntimeError("Claude Code CLI not found (install it or set CLAUDE_BIN)")
    before = {p.parent.name for p in TESTS_DIR.glob("*/test.json")}
    log.parent.mkdir(parents=True, exist_ok=True)
    with open(log, "w", encoding="utf-8") as out:
        subprocess.run([claude, "-p", prompt, *FLAGS], cwd=ROOT, stdout=out, stderr=subprocess.STDOUT, check=False)
    new = sorted({p.parent.name for p in TESTS_DIR.glob("*/test.json")} - before)
    if not new and (limit := usage_limit_message(log.read_text(encoding="utf-8", errors="replace"))):
        raise RuntimeError(f"Claude usage limit reached ({limit}). Run it again after the reset; finished sections are kept.")
    return new


def generate(i: int, n: int, level: str, claude: str) -> bool:
    t0 = time.time()
    print(f"[{i}/{n}] generating…", flush=True)
    log = TESTS_DIR / ".jobs" / f"bank-{i}.log"
    try:
        new = run_generation(f"/toefl-generate full {level}".strip(), log, claude)
    except RuntimeError as e:
        print(f"[{i}/{n}] {e}", flush=True)
        return False
    print(f"[{i}/{n}] {'ready: ' + ', '.join(new) if new else 'FAILED, see ' + str(log)} ({(time.time() - t0) / 60:.1f} min)", flush=True)
    if new:
        log.unlink(missing_ok=True)
    return bool(new)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("n", nargs="?", type=int, default=3)
    ap.add_argument("--level", default="")
    ap.add_argument("--parallel", type=int, default=1)
    a = ap.parse_args()
    claude = os.environ.get("CLAUDE_BIN") or shutil.which("claude")
    if not claude:
        sys.exit("Claude Code CLI not found (install it or set CLAUDE_BIN).")
    with ThreadPoolExecutor(max_workers=max(1, a.parallel)) as pool:
        results = list(pool.map(lambda i: generate(i, a.n, a.level, claude), range(1, a.n + 1)))
    print(f"\n{sum(results)}/{a.n} tests generated. Take the next one with: make next")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
